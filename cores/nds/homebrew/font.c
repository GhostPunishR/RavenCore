/* 16 couleurs : 4 octets par rangée, point x au quartet x (bits 4x à 4x+3). */
void font_load(volatile uint16_t* tiles) {
    for (unsigned glyph = 0; glyph < GLYPH_COUNT; ++glyph) {
        for (unsigned row = 0; row < 8; ++row) {
            const unsigned bits = row < 7 ? glyphs[glyph][row] : 0u;
            uint32_t line = 0;
            for (unsigned x = 0; x < 5; ++x) {
                if ((bits & (0x10u >> x)) != 0) line |= 1u << ((x + 1u) * 4u);
            }
            tiles[(glyph * 8u + row) * 2u] = (uint16_t)line;
            tiles[(glyph * 8u + row) * 2u + 1u] = (uint16_t)(line >> 16u);
        }
    }
}
