// Choix au démarrage, dans l'ordre de la boot ROM : Haut, A + Haut, B + Haut,
// Gauche, A + Gauche, B + Gauche, Bas, A + Bas, B + Bas, Droite, A + Droite,
// B + Droite.
struct ManualChoice {
    std::uint8_t entry;
    std::uint8_t flags;
};
inline constexpr std::array<ManualChoice, 12> manual_choices{{
    {0x12, 0x00}, {0x10, 0x05}, {0x19, 0x03}, {0x18, 0x05}, {0x0d, 0x05}, {0x16, 0x00},
    {0x17, 0x00}, {0x07, 0x00}, {0x1a, 0x05}, {0x05, 0x00}, {0x1c, 0x03}, {0x13, 0x00},
}};

// Le triplet d'une entrée et de ses drapeaux ; celui par défaut s'il manque.
constexpr const CompatibilityPalettes& palettes_of(std::uint8_t entry, std::uint8_t flags) noexcept {
    const PaletteSet* fallback = &palette_sets.front();
    for (const auto& set : palette_sets) {
        if (set.entry == entry && set.flags == flags) return set.palettes;
        if (set.entry == default_entry && set.flags == default_flags) fallback = &set;
    }
    return fallback->palettes;
}

// Somme des 16 octets du titre (0x134 à 0x143) si l'éditeur est Nintendo, 0
// sinon : le B que laisse la boot ROM de la GBC, et la clé de ses palettes.
template <class ReadRom>
constexpr int title_checksum(ReadRom read_rom) {
    const int old_licensee = read_rom(0x014b);
    const bool nintendo = old_licensee == 0x01 ||
        (old_licensee == 0x33 && read_rom(0x0144) == 0x30 && read_rom(0x0145) == 0x31);
    if (!nintendo) return 0;
    int sum = 0;
    for (int address = 0x0134; address <= 0x0143; ++address) sum = (sum + read_rom(address)) & 0xff;
    return sum;
}

// Les palettes que la boot ROM choisit pour un jeu, d'après la somme de son
// titre (0 pour un autre éditeur que Nintendo) et sa 4e lettre (0x137).
constexpr const CompatibilityPalettes& automatic(int checksum, int fourth_letter) noexcept {
    for (const auto& title : title_checksums) {
        if (title.checksum == checksum && (title.fourth_letter == 0 || title.fourth_letter == fourth_letter))
            return palettes_of(title.entry, title.flags);
    }
    return palettes_of(default_entry, default_flags);
}

// Les tables se tiennent : chaque titre et chaque choix renvoie à un triplet,
// aucun titre n'apparaît deux fois, et le triplet par défaut existe.
constexpr bool tables_are_consistent() noexcept {
    const auto known = [](std::uint8_t entry, std::uint8_t flags) {
        for (const auto& set : palette_sets)
            if (set.entry == entry && set.flags == flags) return true;
        return false;
    };
    if (!known(default_entry, default_flags)) return false;
    for (std::size_t index = 0; index < title_checksums.size(); ++index) {
        const auto& title = title_checksums[index];
        if (!known(title.entry, title.flags)) return false;
        for (std::size_t other = index + 1; other < title_checksums.size(); ++other)
            if (title_checksums[other].checksum == title.checksum &&
                (title_checksums[other].fourth_letter == 0 || title.fourth_letter == 0 ||
                 title_checksums[other].fourth_letter == title.fourth_letter))
                return false;
    }
    for (const auto& choice : manual_choices)
        if (!known(choice.entry, choice.flags)) return false;
    return true;
}
static_assert(tables_are_consistent());

